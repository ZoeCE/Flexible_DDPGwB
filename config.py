#   - 保留原有 waypoint/collision/success 奖励
#   - 新增 joint_limit_penalty：关节角接近极限时惩罚
#   - 新增 smoothness_penalty：相邻步关节角变化量惩罚（防抖动）
#   - 移除 action_smooth_penalty（原来针对加速度，现在改为关节空间正则）
