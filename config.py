#
# [ARCH-1] Action Space 重定义
#   旧版：Actor 输出 6D 末端加速度 [ax, ay, az, a_roll, a_pitch, a_yaw]
#   新版：Actor 直接输出 7D 关节角目标 [q1..q7]（关节空间控制）
